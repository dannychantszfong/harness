"""Cross-platform one-shot `harness resume` scheduling.

Used when a subscription runner reports a usage cap. The orchestrator catches
the rate-limit error, asks this module to schedule a resume shortly after the
reset time, and exits cleanly.

Backends:
- macOS: launchd user LaunchAgent
- Linux: systemd user service + timer (experimental, ADR-012)
- Windows: Task Scheduler, registered from an XML task definition, running a
  PowerShell wrapper

Every wrapper resumes with the *absolute* project path and the PATH that was
active when the job was scheduled — scheduler environments (launchd in
particular) otherwise lack ~/.local/bin, npm's prefix, etc., and the resumed
run would not find `claude`/`codex`. Secrets are never written into the
wrappers; API-key env vars must come from the login environment.
"""

from __future__ import annotations

import os
import platform
import shutil
import stat
import subprocess
import tempfile
from datetime import datetime, timedelta
from pathlib import Path
from typing import Optional
from xml.sax.saxutils import escape as xml_escape

# Env vars carried from the scheduling process into the resumed run.
_CARRIED_ENV_VARS: tuple[str, ...] = ("PATH", "HARNESS_SETUP_CONFIG")


def backend() -> str | None:
    system = platform.system()
    if system == "Darwin" and shutil.which("launchctl") is not None:
        return "launchd"
    if system == "Linux" and shutil.which("systemctl") is not None:
        return "systemd"
    if system == "Windows" and shutil.which("schtasks") is not None and _powershell() is not None:
        return "task_scheduler"
    return None


def is_supported() -> bool:
    return backend() is not None


def _label(project_id: str) -> str:
    return f"com.harness.resume.{project_id}"


def _task_name(project_id: str) -> str:
    return f"HarnessResume-{project_id}"


def _plist_path(project_id: str) -> Path:
    return Path.home() / "Library" / "LaunchAgents" / f"{_label(project_id)}.plist"


def _systemd_dir() -> Path:
    return Path.home() / ".config" / "systemd" / "user"


def _systemd_service_path(project_id: str) -> Path:
    return _systemd_dir() / f"{_label(project_id)}.service"


def _systemd_timer_path(project_id: str) -> Path:
    return _systemd_dir() / f"{_label(project_id)}.timer"


def _wrapper_path(project_dir: Path) -> Path:
    return project_dir / ".auto_resume.sh"


def _windows_wrapper_path(project_dir: Path) -> Path:
    return project_dir / ".auto_resume.ps1"


def _log_path(project_dir: Path) -> Path:
    return project_dir / "auto_resume.log"


def _carried_env() -> dict[str, str]:
    return {name: os.environ[name] for name in _CARRIED_ENV_VARS if os.environ.get(name)}


def cancel(project_id: str) -> None:
    """Best-effort: unload/disable/delete any prior schedule for this project."""
    selected = backend()
    if selected == "launchd":
        _cancel_launchd(project_id)
    elif selected == "systemd":
        _cancel_systemd(project_id)
    elif selected == "task_scheduler":
        _cancel_windows(project_id)


def schedule(
    project_dir: Path,
    project_id: str,
    fire_at_utc: datetime,
    harness_binary: Optional[str] = None,
    buffer_seconds: int = 300,
) -> dict:
    """Schedule one `harness resume` invocation slightly after fire_at_utc."""
    selected = backend()
    if selected is None:
        raise RuntimeError(
            "Auto-resume is not supported on this platform. "
            "Supported backends: macOS launchd, Linux systemd --user, Windows Task Scheduler."
        )

    fire_utc = fire_at_utc + timedelta(seconds=buffer_seconds)
    fire_local = fire_utc.astimezone()
    project_dir = project_dir.resolve()
    harness_binary = harness_binary or shutil.which("harness") or "harness"

    if selected == "launchd":
        return _schedule_launchd(project_dir, project_id, fire_local, fire_utc, harness_binary)
    if selected == "systemd":
        return _schedule_systemd(project_dir, project_id, fire_local, fire_utc, harness_binary)
    return _schedule_windows(project_dir, project_id, fire_local, fire_utc, harness_binary)


# ── POSIX wrapper (launchd + systemd) ───────────────────────────────────────

def _sh_quote(value: str) -> str:
    """Single-quote for /bin/sh."""
    return "'" + value.replace("'", "'\"'\"'") + "'"


def _sh_env_lines() -> str:
    return "".join(f"export {k}={_sh_quote(v)}\n" for k, v in _carried_env().items())


def _sh_wrapper(project_dir: Path, harness_binary: str, log_path: Path, pre_run: str = "") -> str:
    return f"""#!/bin/sh
# Auto-generated by harness. Fires once when the usage limit is expected to reset.
set -u

{_sh_env_lines()}PROJECT_DIR={_sh_quote(str(project_dir))}
HARNESS={_sh_quote(harness_binary)}
LOG={_sh_quote(str(log_path))}

echo "" >> "$LOG"
echo "[$(date '+%Y-%m-%d %H:%M:%S %z')] auto-resume firing" >> "$LOG"
{pre_run}
cd "$PROJECT_DIR"
"$HARNESS" resume "$PROJECT_DIR" >> "$LOG" 2>&1
EXIT=$?
echo "[$(date '+%Y-%m-%d %H:%M:%S %z')] auto-resume exited $EXIT" >> "$LOG"
exit $EXIT
"""


# ── macOS launchd ────────────────────────────────────────────────────────────

def _cancel_launchd(project_id: str) -> None:
    plist = _plist_path(project_id)
    if not plist.exists():
        return
    label = _label(project_id)
    uid = os.getuid()
    subprocess.run(["launchctl", "bootout", f"gui/{uid}/{label}"], capture_output=True)
    subprocess.run(["launchctl", "unload", str(plist)], capture_output=True)
    _unlink(plist)


def _schedule_launchd(
    project_dir: Path,
    project_id: str,
    fire_local: datetime,
    fire_utc: datetime,
    harness_binary: str,
) -> dict:
    plist = _plist_path(project_id)
    wrapper = _wrapper_path(project_dir)
    log = _log_path(project_dir)
    label = _label(project_id)

    _cancel_launchd(project_id)
    plist.parent.mkdir(parents=True, exist_ok=True)
    log.touch(exist_ok=True)
    _write_executable(wrapper, _launchd_wrapper_script(project_dir, harness_binary, plist, label, log))
    plist.write_text(_plist_xml(label, wrapper, log, fire_local))

    uid = os.getuid()
    bootstrap = subprocess.run(
        ["launchctl", "bootstrap", f"gui/{uid}", str(plist)],
        capture_output=True,
        text=True,
    )
    if bootstrap.returncode != 0:
        load = subprocess.run(["launchctl", "load", str(plist)], capture_output=True, text=True)
        if load.returncode != 0:
            raise RuntimeError(
                f"launchctl could not load {plist}: {load.stderr or bootstrap.stderr}"
            )

    return {
        "backend": "launchd",
        "label": label,
        "plist": plist,
        "wrapper": wrapper,
        "log": log,
        "fire_local": fire_local,
        "fire_utc": fire_utc,
        "cancel": f"launchctl bootout gui/$(id -u)/{label}",
    }


def _launchd_wrapper_script(
    project_dir: Path,
    harness_binary: str,
    plist_path: Path,
    label: str,
    log_path: Path,
) -> str:
    # The job unloads itself before resuming so it can never fire twice.
    pre_run = (
        f"launchctl bootout \"gui/$(id -u)/{label}\" 2>/dev/null\n"
        f"launchctl unload {_sh_quote(str(plist_path))} 2>/dev/null\n"
    )
    return _sh_wrapper(project_dir, harness_binary, log_path, pre_run=pre_run)


def _plist_xml(label: str, wrapper_path: Path, log_path: Path, fire_local: datetime) -> str:
    return f"""<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTD/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>Label</key>
    <string>{xml_escape(label)}</string>
    <key>ProgramArguments</key>
    <array>
        <string>/bin/sh</string>
        <string>{xml_escape(str(wrapper_path))}</string>
    </array>
    <key>StartCalendarInterval</key>
    <dict>
        <key>Month</key>
        <integer>{fire_local.month}</integer>
        <key>Day</key>
        <integer>{fire_local.day}</integer>
        <key>Hour</key>
        <integer>{fire_local.hour}</integer>
        <key>Minute</key>
        <integer>{fire_local.minute}</integer>
    </dict>
    <key>StandardOutPath</key>
    <string>{xml_escape(str(log_path))}</string>
    <key>StandardErrorPath</key>
    <string>{xml_escape(str(log_path))}</string>
    <key>RunAtLoad</key>
    <false/>
</dict>
</plist>
"""


# ── Linux systemd user timer ─────────────────────────────────────────────────

def _cancel_systemd(project_id: str) -> None:
    timer = _systemd_timer_path(project_id)
    service = _systemd_service_path(project_id)
    subprocess.run(["systemctl", "--user", "disable", "--now", timer.name], capture_output=True)
    _unlink(timer)
    _unlink(service)
    subprocess.run(["systemctl", "--user", "daemon-reload"], capture_output=True)


def _systemd_user_session_error() -> str | None:
    """None if `systemctl --user` can reach a user manager, else the reason."""
    proc = subprocess.run(
        ["systemctl", "--user", "show-environment"],
        capture_output=True,
        text=True,
    )
    if proc.returncode == 0:
        return None
    detail = ((proc.stderr or "") + (proc.stdout or "")).strip()
    return detail or f"systemctl --user exited with code {proc.returncode}"


def _schedule_systemd(
    project_dir: Path,
    project_id: str,
    fire_local: datetime,
    fire_utc: datetime,
    harness_binary: str,
) -> dict:
    session_error = _systemd_user_session_error()
    if session_error is not None:
        raise RuntimeError(
            "systemd --user is not reachable (no user D-Bus session — common on "
            "headless or SSH hosts). Run `loginctl enable-linger $USER`, log in "
            f"again, or resume manually with `harness resume {project_dir}`. "
            f"Detail: {session_error}"
        )

    service = _systemd_service_path(project_id)
    timer = _systemd_timer_path(project_id)
    wrapper = _wrapper_path(project_dir)
    log = _log_path(project_dir)
    label = _label(project_id)

    _cancel_systemd(project_id)
    service.parent.mkdir(parents=True, exist_ok=True)
    log.touch(exist_ok=True)
    _write_executable(wrapper, _systemd_wrapper_script(project_dir, harness_binary, log))
    service.write_text(_systemd_service(label, wrapper))
    timer.write_text(_systemd_timer(label, service.name, fire_local))

    subprocess.run(["systemctl", "--user", "daemon-reload"], capture_output=True, check=True)
    subprocess.run(["systemctl", "--user", "enable", "--now", timer.name], capture_output=True, check=True)

    return {
        "backend": "systemd",
        "label": label,
        "service": service,
        "timer": timer,
        "wrapper": wrapper,
        "log": log,
        "fire_local": fire_local,
        "fire_utc": fire_utc,
        "cancel": f"systemctl --user disable --now {timer.name}",
    }


def _systemd_wrapper_script(project_dir: Path, harness_binary: str, log_path: Path) -> str:
    return _sh_wrapper(project_dir, harness_binary, log_path)


def _systemd_service(label: str, wrapper: Path) -> str:
    return f"""[Unit]
Description=Harness auto-resume {label}

[Service]
Type=oneshot
ExecStart=/bin/sh "{wrapper}"
"""


def _systemd_timer(label: str, service_name: str, fire_local: datetime) -> str:
    # Persistent=true: if the machine is asleep/off at the fire time, the
    # timer fires once on the next boot/wake instead of being lost.
    return f"""[Unit]
Description=Harness auto-resume timer {label}

[Timer]
OnCalendar={fire_local.strftime('%Y-%m-%d %H:%M:%S')}
Persistent=true
Unit={service_name}

[Install]
WantedBy=timers.target
"""


# ── Windows Task Scheduler ──────────────────────────────────────────────────

def _cancel_windows(project_id: str) -> None:
    subprocess.run(
        ["schtasks", "/Delete", "/TN", _task_name(project_id), "/F"],
        capture_output=True,
    )


def _schedule_windows(
    project_dir: Path,
    project_id: str,
    fire_local: datetime,
    fire_utc: datetime,
    harness_binary: str,
) -> dict:
    task = _task_name(project_id)
    wrapper = _windows_wrapper_path(project_dir)
    log = _log_path(project_dir)
    shell = _powershell() or "powershell"

    _cancel_windows(project_id)
    log.touch(exist_ok=True)
    # UTF-8 *with* BOM: Windows PowerShell 5.1 reads BOM-less scripts in the
    # ANSI code page, which mangles non-ASCII project paths.
    wrapper.write_text(
        _powershell_wrapper(project_dir, harness_binary, log, task),
        encoding="utf-8-sig",
    )

    # An XML definition instead of /SC ONCE /ST /SD: the /SD date format
    # follows the system locale, and /TR quoting breaks on paths with spaces.
    fd, xml_name = tempfile.mkstemp(prefix="harness-task-", suffix=".xml")
    os.close(fd)
    xml_path = Path(xml_name)
    try:
        xml_path.write_text(_task_xml(task, shell, wrapper, project_dir, fire_local), encoding="utf-16")
        proc = subprocess.run(
            ["schtasks", "/Create", "/TN", task, "/XML", str(xml_path), "/F"],
            capture_output=True,
            text=True,
        )
    finally:
        _unlink(xml_path)
    if proc.returncode != 0:
        raise RuntimeError(
            f"schtasks could not create {task}: {(proc.stderr or proc.stdout or '').strip()}"
        )

    return {
        "backend": "task_scheduler",
        "label": task,
        "task": task,
        "wrapper": wrapper,
        "log": log,
        "fire_local": fire_local,
        "fire_utc": fire_utc,
        "cancel": f"schtasks /Delete /TN {task} /F",
    }


def _task_xml(task: str, shell: str, wrapper: Path, project_dir: Path, fire_local: datetime) -> str:
    start = fire_local.strftime("%Y-%m-%dT%H:%M:%S")  # local wall-clock time
    arguments = f'-NoProfile -ExecutionPolicy Bypass -File "{wrapper}"'
    return f"""<?xml version="1.0" encoding="UTF-16"?>
<Task version="1.2" xmlns="http://schemas.microsoft.com/windows/2004/02/mit/task">
  <RegistrationInfo>
    <Description>{xml_escape(f"Harness auto-resume ({task})")}</Description>
  </RegistrationInfo>
  <Triggers>
    <TimeTrigger>
      <StartBoundary>{start}</StartBoundary>
      <Enabled>true</Enabled>
    </TimeTrigger>
  </Triggers>
  <Principals>
    <Principal id="Author">
      <LogonType>InteractiveToken</LogonType>
      <RunLevel>LeastPrivilege</RunLevel>
    </Principal>
  </Principals>
  <Settings>
    <MultipleInstancesPolicy>IgnoreNew</MultipleInstancesPolicy>
    <DisallowStartIfOnBatteries>false</DisallowStartIfOnBatteries>
    <StopIfGoingOnBatteries>false</StopIfGoingOnBatteries>
    <StartWhenAvailable>true</StartWhenAvailable>
    <AllowStartOnDemand>true</AllowStartOnDemand>
    <Enabled>true</Enabled>
    <ExecutionTimeLimit>PT72H</ExecutionTimeLimit>
  </Settings>
  <Actions Context="Author">
    <Exec>
      <Command>{xml_escape(shell)}</Command>
      <Arguments>{xml_escape(arguments)}</Arguments>
      <WorkingDirectory>{xml_escape(str(project_dir))}</WorkingDirectory>
    </Exec>
  </Actions>
</Task>
"""


def _powershell_wrapper(project_dir: Path, harness_binary: str, log_path: Path, task: str) -> str:
    env_lines = "".join(
        f"$env:{name} = '{_ps_quote(value)}'\n" for name, value in _carried_env().items()
    )
    return f"""# Auto-generated by harness. Fires once when the usage limit is expected to reset.
{env_lines}$env:PYTHONUTF8 = '1'
$env:PYTHONIOENCODING = 'utf-8'
$ProjectDir = '{_ps_quote(str(project_dir))}'
$Harness = '{_ps_quote(harness_binary)}'
$Log = '{_ps_quote(str(log_path))}'
$Task = '{_ps_quote(task)}'

Add-Content -Path $Log -Encoding UTF8 -Value ""
Add-Content -Path $Log -Encoding UTF8 -Value "[$(Get-Date -Format o)] auto-resume firing"
schtasks /Delete /TN $Task /F *> $null
Set-Location -LiteralPath $ProjectDir
& $Harness resume $ProjectDir 2>&1 | ForEach-Object {{ "$_" }} | Out-File -FilePath $Log -Append -Encoding utf8
$ExitCode = $LASTEXITCODE
Add-Content -Path $Log -Encoding UTF8 -Value "[$(Get-Date -Format o)] auto-resume exited $ExitCode"
exit $ExitCode
"""


def _powershell() -> str | None:
    return shutil.which("powershell") or shutil.which("pwsh")


def _ps_quote(value: str) -> str:
    return value.replace("'", "''")


# ── shared helpers ───────────────────────────────────────────────────────────

def _write_executable(path: Path, text: str) -> None:
    path.write_text(text)
    path.chmod(path.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP)


def _unlink(path: Path) -> None:
    try:
        path.unlink()
    except FileNotFoundError:
        pass
